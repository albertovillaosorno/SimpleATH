"""Pure source-only checks for pinned profile byte-guard construction."""

from unittest import TestCase

from tools.profiles import guard_mask
from tools.profiles import numbers

ADDRESS = 0x1000
WORD_BYTES = 32
FULL_BYTE = 255
EXPECTED_BYTES = "0x00, 0x01, 0xFF"
EXPECTED_WORD = "0x12, 0x34"


class ProfileByteGuardTests(TestCase):
    """Verify generated byte masks without accessing pinned system images."""

    @staticmethod
    def test_byte_initializer_preserves_order_and_width() -> None:
        """Use exact two-digit C++ hexadecimal initializer byte spelling."""
        assert numbers(b"\0\x01\xff") == EXPECTED_BYTES
        assert numbers(bytearray(b"\x12\x34")) == EXPECTED_WORD
        assert not numbers(b"")

    @staticmethod
    def test_empty_relocations_leave_all_bytes_covered() -> None:
        """A guard with no relocation must check every byte."""
        mask = guard_mask([], ADDRESS)
        assert len(mask) == WORD_BYTES
        assert mask == bytearray([FULL_BYTE] * WORD_BYTES)

    @staticmethod
    def test_relocation_windows_mask_only_intersecting_bytes() -> None:
        """Clip crossing and overlapping relocations to the guard window."""
        mask = guard_mask(
            [
                (ADDRESS - 2, 4, "entry", 0),
                (ADDRESS + 1, 2, "entry", 0),
                (ADDRESS + 31, 8, "entry", 0),
                (ADDRESS + 80, 4, "other", 0),
            ],
            ADDRESS,
        )
        assert mask[:3] == bytearray([0, 0, 0])
        assert mask[3:31] == bytearray([FULL_BYTE] * 28)
        assert mask[31] == 0

    @staticmethod
    def test_exact_right_edge_is_not_masked() -> None:
        """A relocation starting after the window must not affect it."""
        mask = guard_mask([(ADDRESS + WORD_BYTES, 4, "next", 0)], ADDRESS)
        assert mask == bytearray([FULL_BYTE] * WORD_BYTES)
